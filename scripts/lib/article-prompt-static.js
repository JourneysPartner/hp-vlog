- 断定を避け「〜の場合があります」「〜が一般的です」等の穏当な表現を使う
- 事実（法令・通達）と解釈（実務判断）を混同しない
- 本文中に他記事への直接リンクを挿入しない（関連記事導線はサイト側で自動生成）
- 定型の締め文『〜できる状態を目指します』『この記事を読んだあとに〜できるようになります』の類は使わない
  （AIが書いた印象になる）。読者が得られるものは、必要なときだけ自然な言い回しで簡潔に触れる。
  「読み終えたあと／この記事を読めば」の枕も必須ではなく、自然に収まるときだけ使う。

